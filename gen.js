// node gen.js > levels.js  — generates solver-verified Lantern Drift levels, sorted by difficulty.
const LD = require('./core.js');
let seed = +(process.argv[2] || 7);
const rnd = () => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
const ri = n => Math.floor(rnd() * n);

function makeMap(w, h, wallP, ncol, perCol) {
  const g = Array.from({ length: h }, (_, y) => Array.from({ length: w }, (_, x) =>
    (x === 0 || y === 0 || x === w - 1 || y === h - 1) ? '#' : (rnd() < wallP ? '#' : '.')));
  const free = () => { for (;;) { const x = 1 + ri(w - 2), y = 1 + ri(h - 2); if (g[y][x] === '.') return [x, y]; } };
  for (let c = 0; c < ncol; c++) for (let k = 0; k < perCol[c]; k++) {
    let [x, y] = free(); g[y][x] = String.fromCharCode(97 + c);
    [x, y] = free(); g[y][x] = String.fromCharCode(65 + c);
  }
  return g.map(r => r.join(''));
}

function switches(path) { let s = 0; for (let i = 1; i < path.length; i++) if (path[i][0] !== path[i - 1][0]) s++; return s; }

const tiers = [
  // [count, w, h, wallP, ncol, perCol, minLen, maxLen]
  [4, 6, 6, 0.10, 1, [1], 2, 4],
  [4, 7, 7, 0.12, 2, [1, 1], 3, 6],
  [5, 7, 7, 0.14, 2, [2, 1], 5, 9],
  [5, 8, 8, 0.14, 2, [2, 2], 7, 12],
  [5, 8, 8, 0.15, 3, [1, 1, 1], 8, 14],
  [5, 9, 9, 0.16, 3, [2, 1, 1], 10, 18],
];
const out = [];
for (const [count, w, h, wp, nc, pc, lo, hi] of tiers) {
  const cands = [];
  let tries = 0;
  while (cands.length < count * 6 && tries < 40000) {
    tries++;
    const map = makeMap(w, h, wp, nc, pc);
    const b = LD.parse({ map });
    // reject already-solved-any-shrine starts (too easy) is fine to keep; reject trivially solved
    const r = LD.solve(b, b.pieces, 150000);
    if (!r || r.len < lo || r.len > hi) continue;
    const used = new Set(r.path.map(p => p[0])).size;
    if (used < nc) continue;
    const sw = switches(r.path);
    if (nc > 1 && sw < Math.min(3, r.len - 2)) continue; // force interplay between colors
    cands.push({ map, par: r.len, score: r.len * 2 + sw * 3 + Math.log2(r.states), sol: r.path.map(p => p[0] + p[1]).join(' ') });
  }
  cands.sort((a, b2) => b2.score - a.score);
  const pick = cands.slice(0, count).sort((a, b2) => a.score - b2.score);
  process.stderr.write(`tier ${w}x${h} col${nc}: ${cands.length} cands in ${tries} tries, pars ${pick.map(p => p.par)}\n`);
  out.push(...pick);
}
console.log('// generated by gen.js seed ' + process.argv[2] + ' — every level BFS-verified, par = optimal moves');
console.log('window.LEVELS = ' + JSON.stringify(out.map(({ map, par, sol }) => ({ map, par, sol })), null, 0).replace(/\},\{/g, '},\n{') + ';');
